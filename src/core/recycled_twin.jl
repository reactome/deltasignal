"""
Recycled twins (specs/059): a copy of an entity regenerated only by its own
cycle reads the entity's root copies too.

The generator can split one Reactome entity into copies: a root copy (no
producer; at most consumed by a depletion edge) and a RECYCLED copy, made only
by reactions downstream of itself. In TGF-beta, SMAD2 [cytosol] has root copies
that feed SMURF2 binding and a recycled copy, regenerated by MTMR4
dephosphorylating p-SMAD2, that SARA recruits to the receptor. A perturbation
pinned at the root copies never reaches the signaling copy (the only route is
the SMURF2 complex depleting it: the wrong sign). specs/049's `closed_twin`
gives a closed carrier free form the same kind of supply edge; specs/053's
generator merge of such copies welded cycles both ways (held-out -493), so
this rule adds a one-way edge only.

  DS_RECYCLED_TWIN=off  (default) nothing changes.
  DS_RECYCLED_TWIN=on   each recycled copy gains an activating OR in-edge
                        (`recycled_supply`) from every root copy of its entity.

A ROOT copy: every in-edge, if any, is depletion, and it has an out-edge.
A RECYCLED copy: not a root copy, not a carrier free form (carrier_loops.csv),
has a producer that is not depletion or dissociation, every such producer is
downstream of the copy itself, and no root copy of its entity reaches it along
non-depletion edges. An observation still wins: a pinned copy keeps its pin.
"""

const DS_VALID_RECYCLED_TWIN_MODES = Set(["off", "on"])
const RECYCLED_DERIVED_IN = ("depletion", "dissociation")

function recycled_twin_mode()::String
    value = get(ENV, "DS_RECYCLED_TWIN", "off")
    value in DS_VALID_RECYCLED_TWIN_MODES || throw(ArgumentError(
        "DS_RECYCLED_TWIN must be one of $(join(sort(collect(DS_VALID_RECYCLED_TWIN_MODES)), ", ")); got $(repr(value))"))
    return value
end

function _reach(adj::Dict{String, Vector{String}}, starts)
    seen = Set{String}()
    stack = String[]
    for s in starts
        append!(stack, get(adj, s, String[]))
    end
    while !isempty(stack)
        n = pop!(stack)
        n in seen && continue
        push!(seen, n)
        append!(stack, get(adj, n, String[]))
    end
    return seen
end

"""
`(network, rule, edges)`: `network` with a `recycled_supply` edge from each
root copy to each recycled copy of the same entity under `mode`, the rule to
report, and how many edges were added. Under `off` the network is returned as
given.
"""
function apply_recycled_twins(network::ReactionNetwork, mode::String)
    mode == "off" && return network, "off", 0
    entity(nd) = (nd === nothing || nd.reactome_id === nothing || isempty(nd.reactome_id)) ?
                 nothing : nd.reactome_id
    inc = Dict{String, Vector{LogicNetworkEdge}}()
    fwd = Dict{String, Vector{String}}()
    pos = Dict{String, Vector{String}}()   # every edge except depletion
    for e in network.edges
        push!(get!(inc, e.child_uuid, LogicNetworkEdge[]), e)
        push!(get!(fwd, e.parent_uuid, String[]), e.child_uuid)
        e.edge_type == "depletion" || push!(get!(pos, e.parent_uuid, String[]), e.child_uuid)
    end
    listed = network.carrier_loops === nothing ? Set{String}() :
             Set(f for (f, _, _) in network.carrier_loops)
    isroot(u) = haskey(fwd, u) && all(e -> e.edge_type == "depletion", get(inc, u, LogicNetworkEdge[]))
    roots = Dict{String, Vector{String}}()
    for (u, nd) in network.nodes
        rid = entity(nd)
        (rid === nothing || !isroot(u)) && continue
        push!(get!(roots, rid, String[]), u)
    end
    added = LogicNetworkEdge[]
    root_reach = Dict{String, Set{String}}()   # per entity, computed once
    for u in sort!(collect(keys(network.nodes)))
        rid = entity(network.nodes[u])
        (rid === nothing || !haskey(roots, rid) || isroot(u) || u in listed) && continue
        producers = [e.parent_uuid for e in get(inc, u, LogicNetworkEdge[])
                     if !(e.edge_type in RECYCLED_DERIVED_IN)]
        isempty(producers) && continue
        u in get!(() -> _reach(pos, roots[rid]), root_reach, rid) && continue
        down = _reach(fwd, (u,))
        all(p -> p in down, producers) || continue
        for r in sort(roots[rid])
            push!(added, LogicNetworkEdge(r, u, false, true, 1.0, "recycled_supply"))
        end
    end
    isempty(added) && return network, mode, 0
    out = ReactionNetwork(network.nodes, vcat(network.edges, added), network.set_mappings,
                          network.cofactor_stids, network.containment, network.drug_stids,
                          network.pools, network.pathogen_stids, network.carrier_loops,
                          network.node_leaves)
    return out, mode, length(added)
end
